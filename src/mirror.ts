import * as path from 'node:path';
import * as vscode from 'vscode';
import { docxToDiffText } from './convert';
import { getLog } from './log';

/**
 * An optional `.md` mirror written beside a document, meant to be committed.
 * This is what makes a diff show up correctly in Git Graph, GitLens, GitHub
 * pull requests and every other tool that reads git history: none of them
 * need to know about GitDoc, because a mirror is just an ordinary tracked
 * text file that git already knows how to diff.
 *
 * GitDoc never creates a mirror on its own — only "Write Markdown Mirror(s)"
 * does, after saying how many and where. Once a mirror exists, it is kept
 * current on every save by default (`gitdoc.markdownMirror: onChange`).
 */

export function mirrorUriFor(source: vscode.Uri): vscode.Uri {
  const withoutExt = source.path.replace(/\.(docx|docm|dotx|dotm)$/i, '');
  return source.with({ path: `${withoutExt}.docx.md` });
}

function mirrorMode(): 'off' | 'onChange' {
  return vscode.workspace.getConfiguration('gitdoc').get<string>('markdownMirror', 'onChange') === 'off'
    ? 'off'
    : 'onChange';
}

async function exists(uri: vscode.Uri): Promise<boolean> {
  try {
    await vscode.workspace.fs.stat(uri);
    return true;
  } catch {
    return false;
  }
}

async function writeMirror(source: vscode.Uri, target: vscode.Uri, read: (uri: vscode.Uri) => PromiseLike<Uint8Array>): Promise<void> {
  const text = await docxToDiffText(await read(source));
  const name = path.posix.basename(source.path);
  const contents = `<!-- Generated by GitDoc from ${name}. Edit the document, not this file. -->\n\n${text}`;
  await vscode.workspace.fs.writeFile(target, new TextEncoder().encode(contents));
}

/** Rewrites a mirror only if it already exists. Called on every document change. */
export async function refreshExistingMirror(source: vscode.Uri, read: (uri: vscode.Uri) => PromiseLike<Uint8Array>): Promise<void> {
  if (mirrorMode() !== 'onChange') {
    return;
  }
  const target = mirrorUriFor(source);
  if (!await exists(target)) {
    return;
  }
  try {
    await writeMirror(source, target, read);
  } catch (error: unknown) {
    getLog().error(`Refreshing the mirror of ${path.basename(source.path)} failed.`, error);
  }
}

export async function writeMirrorForCommand(target: vscode.Uri | undefined): Promise<void> {
  if (!target) {
    void vscode.window.showWarningMessage('GitDoc: open or select a Word document first.');
    return;
  }
  try {
    await writeMirror(target, mirrorUriFor(target), (uri) => vscode.workspace.fs.readFile(uri));
    void vscode.window.showInformationMessage(`GitDoc wrote ${path.basename(mirrorUriFor(target).path)}.`);
  } catch (error: unknown) {
    getLog().error(`Writing the mirror of ${path.basename(target.path)} failed.`, error);
    void vscode.window.showWarningMessage(`GitDoc: could not write a mirror for ${path.basename(target.path)}.`);
  }
}

export async function writeWorkspaceMirrors(): Promise<void> {
  const documents = await vscode.workspace.findFiles('**/*.{docx,docm,dotx,dotm}', '**/node_modules/**');
  if (documents.length === 0) {
    void vscode.window.showInformationMessage('GitDoc: no Word documents in this workspace.');
    return;
  }
  const choice = await vscode.window.showWarningMessage(
    `Write a Markdown mirror for ${documents.length} document${documents.length === 1 ? '' : 's'}?`,
    {
      modal: true,
      detail: 'A .docx.md file is written beside each document, replacing any existing mirror. '
        + 'Commit it alongside the document so Git Graph and pull requests can show a readable diff.',
    },
    'Write mirrors',
  );
  if (choice !== 'Write mirrors') {
    return;
  }

  let written = 0;
  const failures: string[] = [];
  await vscode.window.withProgress(
    { location: vscode.ProgressLocation.Notification, title: 'GitDoc: writing Markdown mirrors' },
    async (progress) => {
      for (const [index, document] of documents.entries()) {
        progress.report({ message: `${index + 1} of ${documents.length}`, increment: 100 / documents.length });
        try {
          await writeMirror(document, mirrorUriFor(document), (uri) => vscode.workspace.fs.readFile(uri));
          written += 1;
        } catch (error: unknown) {
          getLog().error(`Mirroring ${path.basename(document.path)} failed.`, error);
          failures.push(path.basename(document.path));
        }
      }
    },
  );

  void vscode.window.showInformationMessage(
    failures.length === 0
      ? `GitDoc wrote ${written} Markdown mirror${written === 1 ? '' : 's'}.`
      : `GitDoc wrote ${written} mirror${written === 1 ? '' : 's'}; ${failures.length} failed. See the GitDoc log.`,
  );
}
