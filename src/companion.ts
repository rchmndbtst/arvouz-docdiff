import * as path from 'node:path';
import * as vscode from 'vscode';
import { docxToDiffText } from './convert';
import { getLog } from './log';

/**
 * An optional `.md` companion written beside a document, meant to be committed.
 * This is what makes a diff show up correctly in Git Graph, GitLens, GitHub
 * pull requests and every other tool that reads git history: none of them
 * need to know about DocDiff, because a companion is just an ordinary tracked
 * text file that git already knows how to diff.
 *
 * DocDiff never creates a companion on its own — only "Write Markdown Companion(s)"
 * does, after saying how many and where. Once a companion exists, it is kept
 * current on every save by default (`docdiff.autoUpdateCompanions`).
 */

export function companionUriFor(source: vscode.Uri): vscode.Uri {
  const withoutExt = source.path.replace(/\.(docx|docm|dotx|dotm)$/i, '');
  return source.with({ path: `${withoutExt}.docx.md` });
}

function autoUpdate(): boolean {
  return vscode.workspace.getConfiguration('docdiff').get<boolean>('autoUpdateCompanions', true);
}

async function exists(uri: vscode.Uri): Promise<boolean> {
  try {
    await vscode.workspace.fs.stat(uri);
    return true;
  } catch {
    return false;
  }
}

async function writeCompanion(source: vscode.Uri, target: vscode.Uri, read: (uri: vscode.Uri) => PromiseLike<Uint8Array>): Promise<void> {
  const text = await docxToDiffText(await read(source));
  const name = path.posix.basename(source.path);
  const contents = `<!-- Generated by DocDiff from ${name}. Edit the document, not this file. -->\n\n${text}`;
  await vscode.workspace.fs.writeFile(target, new TextEncoder().encode(contents));
}

/** Rewrites a companion only if it already exists. Called on every document change. */
export async function refreshExistingCompanion(source: vscode.Uri, read: (uri: vscode.Uri) => PromiseLike<Uint8Array>): Promise<void> {
  if (!autoUpdate()) {
    return;
  }
  const target = companionUriFor(source);
  if (!await exists(target)) {
    return;
  }
  try {
    await writeCompanion(source, target, read);
  } catch (error: unknown) {
    getLog().error(`Refreshing the companion of ${path.basename(source.path)} failed.`, error);
  }
}

export async function writeCompanionForCommand(target: vscode.Uri | undefined): Promise<void> {
  if (!target) {
    void vscode.window.showWarningMessage('DocDiff: open or select a Word document first.');
    return;
  }
  try {
    await writeCompanion(target, companionUriFor(target), (uri) => vscode.workspace.fs.readFile(uri));
    void vscode.window.showInformationMessage(`DocDiff wrote ${path.basename(companionUriFor(target).path)}.`);
  } catch (error: unknown) {
    getLog().error(`Writing the companion of ${path.basename(target.path)} failed.`, error);
    void vscode.window.showWarningMessage(`DocDiff: could not write a companion for ${path.basename(target.path)}.`);
  }
}

export async function writeWorkspaceCompanions(): Promise<void> {
  const documents = await vscode.workspace.findFiles('**/*.{docx,docm,dotx,dotm}', '**/node_modules/**');
  if (documents.length === 0) {
    void vscode.window.showInformationMessage('DocDiff: no Word documents in this workspace.');
    return;
  }
  const choice = await vscode.window.showWarningMessage(
    `Write a Markdown companion for ${documents.length} document${documents.length === 1 ? '' : 's'}?`,
    {
      modal: true,
      detail: 'A .docx.md file is written beside each document, replacing any existing companion. '
        + 'Commit it alongside the document so Git Graph and pull requests can show a readable diff.',
    },
    'Write companions',
  );
  if (choice !== 'Write companions') {
    return;
  }

  let written = 0;
  const failures: string[] = [];
  await vscode.window.withProgress(
    { location: vscode.ProgressLocation.Notification, title: 'DocDiff: writing Markdown companions' },
    async (progress) => {
      for (const [index, document] of documents.entries()) {
        progress.report({ message: `${index + 1} of ${documents.length}`, increment: 100 / documents.length });
        try {
          await writeCompanion(document, companionUriFor(document), (uri) => vscode.workspace.fs.readFile(uri));
          written += 1;
        } catch (error: unknown) {
          getLog().error(`Writing the companion of ${path.basename(document.path)} failed.`, error);
          failures.push(path.basename(document.path));
        }
      }
    },
  );

  void vscode.window.showInformationMessage(
    failures.length === 0
      ? `DocDiff wrote ${written} Markdown companion${written === 1 ? '' : 's'}.`
      : `DocDiff wrote ${written} companion${written === 1 ? '' : 's'}; ${failures.length} failed. See the DocDiff log.`,
  );
}
